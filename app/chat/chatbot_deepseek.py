# ── 유틸 ────────────────────────────────────────────────────────────────────

DIVIDER      = "─" * 60
THIN_DIVIDER = "·" * 60

def print_meta(turn, elapsed):
    print(f"\n{THIN_DIVIDER}")
    print(f"  턴 {turn}  |  응답 시간: {elapsed:.2f}초  |  모델: {MODEL_NAME}")
    print(THIN_DIVIDER)

def print_bot(text):
    print(f"\n🤖  {text}\n")

def print_user_prompt():
    return input("👤  나: ").strip()

# ── 메인 루프 ────────────────────────────────────────────────────────────────

def main():
    print(f"\n{DIVIDER}")
    print(f"  쇼핑 고민 챗봇  |  모델: {MODEL_NAME}")
    print(f"{DIVIDER}")
    print("  종료하려면 'q' 또는 'quit' 입력.")
    print(f"{DIVIDER}\n")

    messages = [{"role": "system", "content": "(터미널 테스트용: 실제 실행 시 build_system_prompt(data)로 교체)"}]
    turn = 0
    total_elapsed = 0.0

    def call_api(msgs):
        return _get_client().chat.completions.create(model=MODEL_NAME, messages=msgs)

    # 첫 답변 자동 시작
    turn += 1
    messages.append({"role": "user", "content": "대화를 시작해줘. 첫 답변 규칙에 따라 2문장으로 시작해."})
    t0 = time.time()
    resp = call_api(messages)
    elapsed = time.time() - t0
    total_elapsed += elapsed
    bot_msg = resp.choices[0].message.content
    messages.append({"role": "assistant", "content": bot_msg})
    print_meta(turn, elapsed)
    print_bot(bot_msg)

    while True:
        user_input = print_user_prompt()
        if not user_input:
            continue

        if user_input.lower() in ("q", "quit", "종료", "그만"):
            print(f"\n{DIVIDER}")
            print(f"  [EXIT]  |  총 턴: {turn}  |  총 소요 시간: {total_elapsed:.2f}초")
            print(f"{DIVIDER}")

            messages.append({
                "role": "user",
                "content": (
                    "대화가 [EXIT] 신호로 종료됩니다. "
                    "전체 대화에서 드러난 유저의 구매 판단 태도를 분석하고, "
                    "마지막 유저 발화는 최종 결정 신호로 참고하세요. "
                    "반드시 'CODE: 코드명' 형식으로만 출력하세요. 다른 말은 하지 마세요."
                )
            })
            t0 = time.time()
            resp = call_api(messages)
            elapsed = time.time() - t0
            code_output = resp.choices[0].message.content.strip()
            print(f"\n  태도 보정 코드 분석 ({elapsed:.2f}초)")
            print(f"  {code_output}")
            print(f"{DIVIDER}\n")
            break

        messages.append({"role": "user", "content": user_input})
        turn += 1
        t0 = time.time()
        resp = call_api(messages)
        elapsed = time.time() - t0
        total_elapsed += elapsed
        bot_msg = resp.choices[0].message.content
        messages.append({"role": "assistant", "content": bot_msg})
        print_meta(turn, elapsed)
        print_bot(bot_msg)


if __name__ == "__main__":
    main()